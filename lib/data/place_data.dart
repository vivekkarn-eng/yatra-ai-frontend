class YatraSaved {
  static final Set<String> names = <String>{};

  static bool isSaved(String name) => names.contains(name);

  static void toggle(String name) {
    if (names.contains(name)) {
      names.remove(name);
    } else {
      names.add(name);
    }
  }
}